export async function fixtureAdminRequest(path: string, init: RequestInit): Promise<unknown> {
  if (path === "/v1/admin/health") {
    return { status: "ok", version: "3.0.0 · preview", model: "dgb1", time: now / 1000 };
  }
  if (path === "/v1/admin/system") return system;
  if (path === "/v1/admin/training/status") return training;
  if (path === "/v1/admin/models") return { models };
  if (path === "/v1/admin/pipeline/status") {
    return {
      model_id: "dgb1",
      status: "running",
      updated_at: new Date(now - 45_000).toISOString(),
      stages: [
        { name: "source_ingestion", status: "completed", files: 14 },
        { name: "normalization", status: "completed", records: 12480 },
        { name: "quality_scoring", status: "running", progress: 0.68 },
        { name: "token_sharding", status: "pending" }
      ],
      note: "Illustrative development fixture; not read from a real pipeline."
    };
  }
  if (path.startsWith("/v1/admin/metrics/history")) {
    return { epoch_history: training.epoch_history, step_history: stepHistory };
  }

  const method = init.method ?? "GET";
  if (path === "/v1/admin/training/launch" && method === "POST") {
    training = { ...training, is_running: true, elapsed_sec: 1, epoch: 1 };
    return { status: "started", pid: 24810 };
  }
  if (path === "/v1/admin/training/stop" && method === "POST") {
    training = { ...training, is_running: false };
    return { status: "stopped" };
  }
  if (path === "/v1/admin/pipeline/run" && method === "POST") {
    return { status: "started", pid: 24811 };
  }
  if (path === "/v1/admin/models/deploy" || path === "/v1/admin/models/rollback") {
    const body = JSON.parse(String(init.body ?? "{}")) as { model?: string };
    return { status: "queued", model: body.model ?? "unknown" };
  }
  throw new Error(`No development fixture exists for ${method} ${path}`);
}

export function fixtureAssistantAnswer(prompt: string): string {
  const trimmed = prompt.trim();
  return [
    `I’ve got your note${trimmed ? ` about “${trimmed.slice(0, 70)}${trimmed.length > 70 ? "…" : ""}”` : ""}.`,
    "",
    "This response is generated by the DGB **local UI preview** so you can test the conversation layout, saved history, and artifact actions without a running model.",
    "",
    "In the connected workspace, this reply comes from the authenticated `/v1/chat/completions` streaming endpoint."
  ].join("\n");
}

